"""Structured summary of a clip: setting, characters, the gist of the dialogue, actions
and key moments.

It is generated by the LLM from the transcript (with who speaks), the confirmed
characters, the notable sounds and the source title, then reviewed by the person:
accepted as is, edited section by section, or written by hand from scratch. Every item
says whether it is reliable: the model's own confidence is not enough, an item counts
as reliable only when it is backed by lines of the transcript it cites (or, for a
character, by a confirmed face / a name heard in the dialogue). The LLM cannot see
the picture, so actions it infers stay "предположение" unless a line supports them.

A section the person edited is never overwritten by a new generation. The summary
(reliable items as facts, the rest marked as guesses) goes into the analysis prompt.
Stored in `<job>/summary.json`.
"""
from __future__ import annotations

import json
import logging
import re
import time
from dataclasses import asdict, dataclass, field
from pathlib import Path

log = logging.getLogger(__name__)
FILE = "summary.json"
SECTIONS = {
    "setting": "Обстановка",
    "characters": "Персонажи",
    "dialogue": "Суть диалога",
    "actions": "Действия",
    "moments": "Ключевые моменты",
}
UNSURE = "?"   # the prefix of an uncertain line in the editable text
_T = r"(?:\d+:)?\d+(?:[.,]\d+)?"
# "12.9 с — …", "0:12 - …", "0.0–4.0 с: …" at the start of a moment's text (the time is stored separately)
_LEAD_TIME = re.compile(rf"^{_T}(?:\s*[–-]\s*{_T})?\s*(?:(?:с|сек|s)\.?\s*[—–:,-]?|[—–:,-])\s*")


@dataclass
class Item:
    text: str
    certain: bool = False
    name: str = ""                 # characters: who
    time: float | None = None      # moments: when (s, clip time)


@dataclass
class Summary:
    setting: list[Item] = field(default_factory=list)
    characters: list[Item] = field(default_factory=list)
    dialogue: list[Item] = field(default_factory=list)
    actions: list[Item] = field(default_factory=list)
    moments: list[Item] = field(default_factory=list)
    edited: dict[str, bool] = field(default_factory=dict)   # section -> written/changed by the person
    status: str = "draft"          # draft | accepted
    source: str = "auto"           # auto | manual (written by hand)
    model: str = ""
    notes: list[str] = field(default_factory=list)
    updated: float = 0.0

    # ------------------------------------------------------------ persistence
    @classmethod
    def exists(cls, job_dir: Path) -> bool:
        return (job_dir / FILE).exists()

    @classmethod
    def load(cls, job_dir: Path) -> "Summary | None":
        p = job_dir / FILE
        if not p.exists():
            return None
        d = json.loads(p.read_text())
        out = cls(**{k: v for k, v in d.items() if k not in SECTIONS and k in cls.__dataclass_fields__})
        for sec in SECTIONS:
            setattr(out, sec, [Item(**x) for x in d.get(sec, [])])
        return out

    def save(self, job_dir: Path) -> None:
        self.updated = time.time()
        tmp = job_dir / (FILE + ".tmp")
        tmp.write_text(json.dumps(asdict(self), ensure_ascii=False, indent=1))
        tmp.replace(job_dir / FILE)

    # ------------------------------------------------------------ views
    def items(self, sec: str) -> list[Item]:
        return getattr(self, sec)

    def empty(self) -> bool:
        return not any(self.items(s) for s in SECTIONS)

    def counts(self) -> tuple[int, int]:
        all_items = [i for s in SECTIONS for i in self.items(s)]
        return sum(1 for i in all_items if i.certain), sum(1 for i in all_items if not i.certain)


# ================================================================ text form (the editor)
def _fmt_time(t: float) -> str:
    m, s = divmod(max(0.0, t), 60)
    return f"{int(m)}:{s:04.1f}"


def to_text(s: Summary, sec: str) -> str:
    lines = []
    for it in s.items(sec):
        prefix = "" if it.certain else f"{UNSURE} "
        if sec == "characters" and it.name:
            lines.append(f"{prefix}{it.name} — {it.text}")
        elif sec == "moments" and it.time is not None:
            lines.append(f"{prefix}{_fmt_time(it.time)} — {it.text}")
        else:
            lines.append(f"{prefix}{it.text}")
    return "\n".join(lines)


_TIME = re.compile(r"^(?:(\d+):)?(\d+(?:[.,]\d+)?)\s*[—–-]\s*(.+)$")


def from_text(sec: str, text: str) -> tuple[list[Item], list[str]]:
    """Items from the editor's text: one per line, "? " marks a guess; characters
    "Имя — описание", moments "0:12 — что происходит". Lines written by the person
    are reliable unless they start with "?"."""
    items, errs = [], []
    for n, raw in enumerate((text or "").splitlines(), 1):
        line = " ".join(raw.split())
        if not line:
            continue
        certain = not line.startswith(UNSURE)
        line = line.lstrip(UNSURE).strip()
        if not line:
            continue
        if sec == "characters":
            name, sep, desc = line.partition(" — ")
            if not sep:
                name, sep, desc = line.partition(" - ")
            items.append(Item(desc.strip() if sep else "", certain, name=name.strip()))
        elif sec == "moments":
            m = _TIME.match(line)
            if not m:
                errs.append(f"{SECTIONS[sec]}, строка {n}: начните со времени — «0:12 — что происходит».")
                continue
            t = float(m.group(1) or 0) * 60 + float(m.group(2).replace(",", "."))
            items.append(Item(m.group(3).strip(), certain, time=round(t, 1)))
        else:
            items.append(Item(line, certain))
    return items, errs


def edit(s: Summary, sec: str, text: str) -> list[str]:
    """Apply the editor's text to a section (marks it as edited when it changed)."""
    items, errs = from_text(sec, text)
    if errs:
        return errs
    if to_text(s, sec).strip() != to_text(Summary(**{sec: items}), sec).strip():
        setattr(s, sec, items)
        s.edited[sec] = True
        s.status = "draft"
    return []


def manual() -> Summary:
    """An empty summary the person fills in by hand."""
    return Summary(edited={sec: True for sec in SECTIONS}, source="manual", model="вручную")


# ================================================================ generation
def _prompt(lines: list[str], title: str, cast_line: str, sounds_line: str, note: str, duration: float) -> str:
    return (
        "Ты помогаешь разобрать сцену из видео. Видео ты не видишь — только расшифровку речи "
        "с таймкодами и номерами реплик, данные о персонажах и звуках.\n"
        + (f"Название ролика: {title}\n" if title else "")
        + (f"{cast_line}\n" if cast_line else "")
        + (f"{sounds_line}\n" if sounds_line else "")
        + (f"Заметка автора: {note}\n" if note else "")
        + f"Длительность фрагмента: {duration:.0f} с.\nРеплики:\n" + "\n".join(lines) + "\n\n"
        "Составь краткую структурированную сводку по-русски. Для каждого пункта укажи, на какие реплики он "
        "опирается (их номера в evidence), и certain = true, только если пункт прямо следует из реплик. "
        "Догадки о внешности, месте, жестах и действиях, которых не слышно в речи, — certain = false. "
        "Не выдумывай имён: используй имена из данных о персонажах или прозвучавшие в репликах.\n"
        "Ответь JSON:\n"
        '{"setting": {"text": "где и в какой ситуации происходит разговор", "certain": bool, "evidence": [номера]},\n'
        ' "characters": [{"name": "имя", "text": "кто это и чего хочет в сцене", "certain": bool, "evidence": [номера]}],\n'
        ' "dialogue": {"text": "суть разговора в 1–2 предложениях", "certain": bool, "evidence": [номера]},\n'
        ' "actions": [{"text": "что делают герои", "certain": bool, "evidence": [номера]}],\n'
        ' "moments": [{"time": секунда, "text": "поворотный момент", "certain": bool, "evidence": [номера]}]}\n'
        "Ключевых моментов — 2–5, действий — до 4."
    )


def _schema() -> dict:
    item = {"type": "object", "properties": {"text": {"type": "string"}, "certain": {"type": "boolean"},
                                             "evidence": {"type": "array", "items": {"type": "integer"}}},
            "required": ["text", "certain"]}
    char = {"type": "object", "properties": {**item["properties"], "name": {"type": "string"}}, "required": ["name", "text", "certain"]}
    moment = {"type": "object", "properties": {**item["properties"], "time": {"type": "number"}}, "required": ["time", "text", "certain"]}
    return {"type": "object", "properties": {
        "setting": item, "characters": {"type": "array", "items": char}, "dialogue": item,
        "actions": {"type": "array", "items": item}, "moments": {"type": "array", "items": moment}},
        "required": ["setting", "characters", "dialogue", "actions", "moments"]}


def build(data: dict, seg_ids: set[int], seg_text: str, known_names: set[str], duration: float) -> Summary:
    """Summary from the LLM's JSON with our own reliability rules applied."""
    def backed(x: dict) -> bool:
        ev = x.get("evidence") or []
        try:
            ev = [int(v) for v in ev]
        except (TypeError, ValueError):
            ev = []
        return bool(x.get("certain")) and any(v in seg_ids for v in ev)

    def one(x) -> list[Item]:
        if isinstance(x, list):
            x = x[0] if x else {}
        text = " ".join(str((x or {}).get("text") or "").split())
        return [Item(text, backed(x))] if text else []

    def strip_lead(text: str, lead: str) -> str:  # models like to repeat the name / the time in the text
        return re.sub(rf"^{re.escape(lead)}\s*[—–:,-]\s*", "", text, flags=re.I) if lead else text

    s = Summary()
    s.setting = one(data.get("setting"))
    s.dialogue = one(data.get("dialogue"))
    low = seg_text.lower()
    for x in data.get("characters") or []:
        name = " ".join(str(x.get("name") or "").split())
        text = " ".join(str(x.get("text") or "").split())
        if not name:
            continue
        sure_name = name.lower() in known_names or (len(name) > 2 and name.lower() in low)
        text = strip_lead(text, name)
        if text:  # a known name makes the name reliable, not the description: that needs cited lines
            s.characters.append(Item(text, sure_name and backed(x), name=name))
    for x in (data.get("actions") or [])[:6]:
        s.actions += one(x)
    for x in (data.get("moments") or [])[:8]:
        text = " ".join(str(x.get("text") or "").split())
        try:
            t = float(x.get("time"))
        except (TypeError, ValueError):
            t = None
        text = _LEAD_TIME.sub("", text)
        if not text:
            continue
        ok_time = t is not None and 0 <= t <= duration + 0.5
        s.moments.append(Item(text, backed(x) and ok_time, time=round(t, 1) if ok_time else None))
    s.moments.sort(key=lambda i: (i.time is None, i.time or 0))
    return s


def generate(segments, provider, *, names: dict[str, str] | None = None, label_name: dict[str, str] | None = None,
             label_of: dict[int, str | None] | None = None, title: str = "", cast_line: str = "", sounds_line: str = "",
             note: str = "", known_names: set[str] | None = None, duration: float = 0.0) -> Summary:
    """Ask the LLM; raises llm.LLMError (and friends) as is, so the UI can offer another model."""
    import analyzer

    label_name = label_name or {}
    label_of = label_of or {}
    lines = []
    for sg in segments:
        who = label_name.get(label_of.get(sg.id) or "", "")
        lines.append(f"[{sg.id}] {sg.start:.1f}–{sg.end:.1f} с{f' {who}:' if who else ':'} {sg.text.strip()}")
    if not lines:
        raise ValueError("В клипе не нашлось речи — сводку можно написать только вручную.")
    reply = provider.chat([{"role": "user", "content": _prompt(lines, title, cast_line, sounds_line, note, duration)}],
                          _schema())
    data = analyzer.extract_json(reply)
    if not isinstance(data, dict):
        raise ValueError("Нейросеть вернула сводку в непонятном виде.")
    s = build(data, {sg.id for sg in segments}, " ".join(sg.text for sg in segments),
              {n.lower() for n in (known_names or set())}, duration)
    if s.empty():
        raise ValueError("Нейросеть вернула пустую сводку.")
    sure, unsure = s.counts()
    log.info("✓ Сводка сцены: надёжных пунктов %d, предположений %d", sure, unsure)
    return s


def merge(old: Summary | None, new: Summary) -> Summary:
    """A new generation keeps every section the person edited."""
    if old is None:
        return new
    for sec in SECTIONS:
        if old.edited.get(sec):
            setattr(new, sec, old.items(sec))
            new.edited[sec] = True
    new.source = "auto"
    return new


def context_text(s: Summary | None) -> str:
    """The summary for the analysis prompt: reliable items as facts, guesses marked."""
    if s is None or s.empty():
        return ""
    head = "Сводка сцены (проверена человеком)" if s.status == "accepted" else "Сводка сцены (черновик)"
    parts = []
    for sec, title in SECTIONS.items():
        items = s.items(sec)
        if not items:
            continue
        rendered = []
        for it in items:
            body = f"{it.name} — {it.text}" if it.name else (f"{_fmt_time(it.time)} {it.text}" if it.time is not None else it.text)
            rendered.append(body if it.certain else f"{body} (предположение)")
        parts.append(f"{title}: " + "; ".join(rendered))
    return head + ". " + ". ".join(parts) + "."
